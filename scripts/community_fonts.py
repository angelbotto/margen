#!/usr/bin/env python3
"""Rebuild or verify the frozen community font bundle.

    python3 scripts/community_fonts.py --check
    python3 scripts/community_fonts.py --rebuild  # downloads pinned, hashed WOFF2
    python3 scripts/community_fonts.py --check --inspect

Rebuild/check require only the Python standard library. Optional --inspect also
uses fontTools to decode every table and verify glyph coverage and variable axes.
If its Brotli extension is absent, the repository's Node runtime decodes Brotli.
No font conversion/subsetting is performed. To update upstream assets, explicitly
review and update the evidence manifest and the complete license files first.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import struct
import subprocess
from types import SimpleNamespace
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'tests/evidence/community-fonts.json'
CSS = ROOT / 'packages/core/styles/community-fonts.css'


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def licenses(manifest: dict) -> list[str]:
    result = []
    for license in manifest['licenses']:
        data = (ROOT / license['path']).read_bytes()
        require(sha256(data) == license['sha256'], f"License changed: {license['path']}")
        text = data.decode('utf-8')
        require('*/' not in text, 'License must be safe in a CSS comment')
        result.append(f"/* {license['family']} — complete upstream license\n{text.rstrip()}\n*/")
    return result


def render(manifest: dict, payloads: list[bytes]) -> str:
    blocks = ['/* Generated by scripts/community_fonts.py; embedded original WOFF2. */']
    blocks.extend(licenses(manifest))
    for face, data in zip(manifest['files'], payloads, strict=True):
        encoded = base64.b64encode(data).decode('ascii')
        blocks.append(
            f"/* {face['family']} / {face['style']} / {face['subset']} */\n"
            '@font-face {\n'
            f"  font-family: '{face['family']}';\n"
            f"  font-style: {face['style']};\n"
            f"  font-weight: {face['weight']};\n"
            '  font-display: swap;\n'
            f"  src: url(data:font/woff2;base64,{encoded}) format('woff2');\n"
            f"  unicode-range: {face['unicode_range']};\n"
            '}'
        )
    return '\n\n'.join(blocks) + '\n'


def validate_payload(face: dict, data: bytes) -> None:
    require(len(data) == face['bytes'], f"Size mismatch: {face['source']}")
    require(sha256(data) == face['sha256'], f"Hash mismatch: {face['source']}")
    require(data[:4] == b'wOF2', 'Invalid WOFF2 signature')
    require(struct.unpack_from('>I', data, 8)[0] == len(data), 'Invalid WOFF2 length')


def unicode_points(ranges: str) -> set[int]:
    points = set()
    for item in ranges.split(', '):
        start, _, end = item.removeprefix('U+').partition('-')
        points.update(range(int(start, 16), int(end or start, 16) + 1))
    return points


def inspect_fonts(manifest: dict, payloads: list[bytes]) -> dict:
    from fontTools.ttLib import TTFont, woff2

    # Read-only fallback: Node includes Brotli in zlib; no pip/npm install needed.
    if not woff2.haveBrotli:
        def decompress(data: bytes) -> bytes:
            return subprocess.run(
                ['node', '-e', "process.stdout.write(require('node:zlib').brotliDecompressSync(require('node:fs').readFileSync(0)))"],
                input=data, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True,
            ).stdout
        woff2.brotli = SimpleNamespace(decompress=decompress)
        woff2.haveBrotli = True

    coverage = {}
    inspections = []
    for face, data in zip(manifest['files'], payloads, strict=True):
        font = TTFont(io.BytesIO(data), lazy=False)
        font.ensureDecompiled()
        cmap = font.getBestCmap()
        axes = {axis.axisTag: [axis.minValue, axis.maxValue] for axis in font['fvar'].axes}
        require(axes['wght'][0] <= 400 and axes['wght'][1] >= 700, 'Missing variable weights')
        require(bool(font['head'].macStyle & 2) == (face['style'] == 'italic'), 'Incorrect italic flag')
        routed = set(cmap) & unicode_points(face['unicode_range'])
        key = (face['family'], face['style'])
        coverage.setdefault(key, set()).update(routed)
        actual = {'glyphs': len(cmap), 'routed_glyphs': len(routed), 'axes': axes}
        if 'inspection' in face:
            require(actual == face['inspection'], f"Font inspection changed: {key}")
        inspections.append(actual)
        font.close()
    for key, points in coverage.items():
        for language, sample in manifest['coverage_samples'].items():
            missing = sorted(set(map(ord, sample)) - points)
            require(not missing, f'{key} missing {language} code points: {missing}')
    return {'faces': inspections, 'family_styles_checked': len(coverage),
            'coverage_samples_passed': list(manifest['coverage_samples'])}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='Check the committed CSS offline (default)')
    mode.add_argument('--rebuild', action='store_true', help='Fetch frozen sources and regenerate only the CSS')
    parser.add_argument('--inspect', action='store_true', help='Decode font tables and check routed glyph coverage')
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    require(len(manifest['files']) == 6, 'Expected six font subset faces')
    if args.rebuild:
        payloads = []
        for face in manifest['files']:
            require(face['source'].startswith('https://fonts.gstatic.com/s/'), 'Unexpected asset host')
            with urllib.request.urlopen(face['source'], timeout=30) as response:
                payloads.append(response.read())
    else:
        text = CSS.read_text()
        payloads = [base64.b64decode(encoded, validate=True) for encoded in
                    re.findall(r'url\(data:font/woff2;base64,([A-Za-z0-9+/=]+)\)', text)]
    require(len(payloads) == len(manifest['files']), 'Embedded font count mismatch')
    for face, data in zip(manifest['files'], payloads, strict=True):
        validate_payload(face, data)
    generated = render(manifest, payloads)
    if args.rebuild:
        CSS.write_text(generated)
    else:
        require(text == generated, 'CSS differs from deterministic font-face + license rendering')
    if args.inspect:
        print(json.dumps(inspect_fonts(manifest, payloads), indent=2))
    print(f"PASS: {len(payloads)} original WOFF2 faces, {sum(map(len, payloads))} font bytes, "
          f"{len(generated.encode())} CSS bytes, complete licenses, zero external runtime URLs")


if __name__ == '__main__':
    main()
