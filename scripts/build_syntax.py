#!/usr/bin/env python3
"""Generate packages/core/components/code.js from Margen's runtime, its CSS and pinned Prism files.

No Node and no network: the vendored files are checked against lock.json before they are used.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'packages/core/syntax/vendor/prismjs-1.30.0'
RUNTIME = ROOT / 'packages/core/syntax/runtime.js'
STYLE = ROOT / 'packages/core/styles/syntax.css'
TARGET = ROOT / 'packages/core/components/code.js'
# Dependency order from Prism's components.json.
LANGUAGES = ['markup', 'css', 'clike', 'javascript', 'typescript', 'jsx', 'tsx', 'json', 'python', 'bash',
             'sql', 'c', 'cpp', 'markdown', 'yaml', 'diff', 'rust', 'go', 'perl']


def vendored():
    lock = json.loads((VENDOR / 'lock.json').read_text())
    pinned = {f['path']: f['sha256'] for f in lock['files']}
    wanted = ['components/prism-core.min.js'] + ['components/prism-' + l + '.min.js' for l in LANGUAGES]
    sources = []
    for path in wanted:
        data = (VENDOR / path).read_bytes()
        if pinned.get(path) != hashlib.sha256(data).hexdigest():
            raise SystemExit('Vendored Prism file differs from lock.json: ' + path)
        sources.append(data.decode('utf-8').strip())
    license = lock['license_file']
    if hashlib.sha256((ROOT / license['path']).read_bytes()).hexdigest() != license['sha256']:
        raise SystemExit('Prism license notice differs from lock.json: ' + license['path'])
    return lock, sources


def generate():
    lock, sources = vendored()
    runtime = RUNTIME.read_text()
    assert runtime.count('MARGEN_PRISM') == 1 and runtime.count('MARGEN_STYLE') == 1, 'runtime placeholders'
    # Prism runs in its own non-strict scope: no window, document, module or global reach it,
    # so it never auto-highlights, registers a worker handler or leaks a global.
    prism = ('(function(window,WorkerGlobalScope,self,module,global,document){\n' + '\n'.join(sources) +
             '\nreturn Prism;})({Prism:{manual:true,disableWorkerMessageHandler:true}})')
    css = STYLE.read_text().strip()
    body = runtime.replace('MARGEN_PRISM', prism).replace('MARGEN_STYLE', json.dumps(css, ensure_ascii=False).replace('<', '\\u003c'))
    header = ('/* GENERATED by scripts/build_syntax.py from packages/core/syntax/runtime.js and packages/core/styles/syntax.css.\n'
              '   Includes Prism ' + lock['version'] + ' (MIT, (c) 2012 Lea Verou; ' + lock['integrity'] + '),\n'
              '   unmodified: core + ' + ', '.join(LANGUAGES) + '. See packages/core/syntax/vendor/prismjs-' + lock['version'] + '/. */\n')
    TARGET.write_text(header + body)
    return TARGET


if __name__ == '__main__':
    path = generate()
    data = path.read_bytes()
    import gzip
    print(f'{path.relative_to(ROOT)}: {len(data)} bytes, {len(gzip.compress(data, 9))} gzip')
